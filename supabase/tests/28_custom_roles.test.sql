-- Feature 04: tenant role definitions are manageable only through guarded, audited functions.
begin;
select plan(24);

select has_function('public', 'tenant_roles_catalog', array['uuid'],
  'members can read the role catalog for their active tenant');
select has_function('public', 'save_custom_role', array['uuid', 'uuid', 'text', 'text[]'],
  'role managers have a transactional custom-role save function');
select ok(
  has_function_privilege('authenticated', 'public.tenant_roles_catalog(uuid)', 'EXECUTE')
  and has_function_privilege('authenticated', 'public.save_custom_role(uuid,uuid,text,text[])', 'EXECUTE')
  and not has_function_privilege('anon', 'public.tenant_roles_catalog(uuid)', 'EXECUTE')
  and not has_function_privilege('anon', 'public.save_custom_role(uuid,uuid,text,text[])', 'EXECUTE')
  and not has_function_privilege('service_role', 'public.save_custom_role(uuid,uuid,text,text[])', 'EXECUTE')
  and not has_function_privilege('public', 'public.save_custom_role(uuid,uuid,text,text[])', 'EXECUTE'),
  'custom role functions are authenticated-only');
select ok(
  not has_table_privilege('authenticated', 'public.roles', 'INSERT,UPDATE,DELETE,TRUNCATE')
  and not has_table_privilege('authenticated', 'public.role_permissions', 'INSERT,UPDATE,DELETE,TRUNCATE')
  and not has_table_privilege('anon', 'public.roles', 'SELECT,INSERT,UPDATE,DELETE,TRUNCATE')
  and not has_table_privilege('service_role', 'public.roles', 'INSERT,UPDATE,DELETE,TRUNCATE'),
  'custom role writes cannot bypass the database functions');

insert into auth.users (id, instance_id, aud, role, email) values
  ('28282828-0000-4000-8000-000000000001', '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', 'roles-owner@example.test'),
  ('28282828-0000-4000-8000-000000000002', '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', 'roles-lead@example.test');
insert into public.tenants (id, name) values
  ('28282828-0000-4000-8000-00000000000a', 'Role tenant A'),
  ('28282828-0000-4000-8000-00000000000b', 'Role tenant B');
select app.seed_system_roles(id) from public.tenants where id in (
  '28282828-0000-4000-8000-00000000000a', '28282828-0000-4000-8000-00000000000b');
insert into public.memberships (tenant_id, user_id) values
  ('28282828-0000-4000-8000-00000000000a', '28282828-0000-4000-8000-000000000001'),
  ('28282828-0000-4000-8000-00000000000a', '28282828-0000-4000-8000-000000000002'),
  ('28282828-0000-4000-8000-00000000000b', '28282828-0000-4000-8000-000000000002');
insert into public.membership_roles (tenant_id, membership_id, role_id)
select m.tenant_id, m.id, r.id from public.memberships m
join public.roles r on r.tenant_id = m.tenant_id and r.key = 'owner'
where m.user_id = '28282828-0000-4000-8000-000000000001';
insert into public.membership_roles (tenant_id, membership_id, role_id)
select m.tenant_id, m.id, r.id from public.memberships m
join public.roles r on r.tenant_id = m.tenant_id and r.key = 'deal_lead'
where m.user_id = '28282828-0000-4000-8000-000000000002' and m.tenant_id = '28282828-0000-4000-8000-00000000000a';

create temporary table custom_role_test_ids (name text primary key, id uuid);
grant all on custom_role_test_ids to public;

set local role authenticated;
select set_config('request.jwt.claims', '{"sub":"28282828-0000-4000-8000-000000000001"}', true);

select is((public.tenant_roles_catalog('28282828-0000-4000-8000-00000000000a')->>'canManageRoles')::boolean,
  true, 'role catalog reports that an Owner can manage roles');
select is(jsonb_array_length(public.tenant_roles_catalog('28282828-0000-4000-8000-00000000000a')->'roles'),
  6, 'catalog lists the tenant system roles');
select throws_ok($$select public.tenant_roles_catalog('28282828-0000-4000-8000-00000000000b')$$,
  '42501', 'permission denied', 'cross-tenant catalog access is denied');
insert into custom_role_test_ids
select 'created', public.save_custom_role('28282828-0000-4000-8000-00000000000a', null, 'Deal Reviewer',
  array['deal.view', 'deal.note']);
select is((select count(*) from public.roles r join custom_role_test_ids t on t.id = r.id
  where r.tenant_id = '28282828-0000-4000-8000-00000000000a' and not r.is_system and r.name = 'Deal Reviewer'),
  1::bigint, 'Owner can create a custom role in their tenant');
select is((select count(*) from public.role_permissions rp join custom_role_test_ids t on t.id = rp.role_id
  where rp.permission in ('deal.view', 'deal.note')), 2::bigint,
  'custom role permissions are saved atomically');
select ok((select r.key ~ '^custom_[a-z]+$' from public.roles r join custom_role_test_ids t on t.id = r.id),
  'custom role key is generated by the database');
select is((select count(*) from public.tenant_events where tenant_id = '28282828-0000-4000-8000-00000000000a'
  and kind = 'role_created'), 1::bigint, 'custom role creation is recorded in the append-only tenant trail');

select public.save_custom_role('28282828-0000-4000-8000-00000000000a',
  (select id from custom_role_test_ids where name = 'created'), 'Senior Deal Reviewer', array['deal.view']);
select is((select r.name from public.roles r join custom_role_test_ids t on t.id = r.id),
  'Senior Deal Reviewer', 'Owner can update the name and permissions of a custom role');
select is((select count(*) from public.role_permissions rp join custom_role_test_ids t on t.id = rp.role_id),
  1::bigint, 'role update replaces its permission set');
select is((select count(*) from public.tenant_events where tenant_id = '28282828-0000-4000-8000-00000000000a'
  and kind = 'role_updated'), 1::bigint, 'custom role update is recorded in the tenant trail');
select ok(exists(select 1 from public.tenant_events where tenant_id = '28282828-0000-4000-8000-00000000000a'
  and kind = 'role_updated' and detail like '%Senior Deal Reviewer permissions=deal.view'),
  'role audit entries snapshot the complete saved permission set');

reset role;
insert into public.membership_roles (tenant_id, membership_id, role_id)
select '28282828-0000-4000-8000-00000000000a', m.id, r.id
from public.memberships m cross join custom_role_test_ids t join public.roles r on r.id = t.id
where m.tenant_id = '28282828-0000-4000-8000-00000000000a'
  and m.user_id = '28282828-0000-4000-8000-000000000002' and t.name = 'created';
set local role authenticated;
select set_config('request.jwt.claims', '{"sub":"28282828-0000-4000-8000-000000000001"}', true);
select throws_ok($$select public.save_custom_role('28282828-0000-4000-8000-00000000000a',
  (select id from custom_role_test_ids where name = 'created'), 'Senior Deal Reviewer', array['approval.decide'])$$,
  '23514', 'separation of duties conflict', 'role update cannot conflict with a permission held by an assigned member');

select throws_ok($$select public.save_custom_role('28282828-0000-4000-8000-00000000000a', null, 'No Permissions', array[]::text[])$$,
  '22023', 'custom role needs at least one permission', 'empty permission sets are rejected');
select throws_ok($$select public.save_custom_role('28282828-0000-4000-8000-00000000000a', null, 'Unknown Permission', array['tenant.admin'])$$,
  '22023', 'unknown permission', 'permissions outside the catalog are rejected');
select throws_ok($$select public.save_custom_role('28282828-0000-4000-8000-00000000000a', null, 'Conflicting Role', array['deal.request_approval', 'approval.decide'])$$,
  '23514', 'separation of duties conflict', 'roles cannot combine conflicting permissions');
select throws_ok($$select public.save_custom_role('28282828-0000-4000-8000-00000000000a',
  (select id from public.roles where tenant_id = '28282828-0000-4000-8000-00000000000a' and key = 'owner'), 'Owner', array['deal.view'])$$,
  '55000', 'system roles are immutable', 'system roles cannot be edited');
select throws_ok($$select public.save_custom_role('28282828-0000-4000-8000-00000000000b', null, 'Other Tenant Role', array['deal.view'])$$,
  '42501', 'permission denied', 'role manager cannot create roles in another tenant');

select set_config('request.jwt.claims', '{"sub":"28282828-0000-4000-8000-000000000002"}', true);
select is((public.tenant_roles_catalog('28282828-0000-4000-8000-00000000000a')->>'canManageRoles')::boolean,
  false, 'ordinary member cannot manage roles');
select throws_ok($$select public.save_custom_role('28282828-0000-4000-8000-00000000000a', null, 'Member Role', array['deal.view'])$$,
  '42501', 'permission denied', 'ordinary member cannot create custom roles');

reset role;
select is((select count(*) from public.tenant_events where tenant_id = '28282828-0000-4000-8000-00000000000a'
  and kind in ('role_created', 'role_updated')), 2::bigint, 'role audit entries remain append-only');

select * from finish();
rollback;
