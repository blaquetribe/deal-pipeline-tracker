// Writes random per-machine development secrets into the untracked .env (ADR 0014).
// Usage: node scripts/gen-dev-env.mjs [path to .env]      (make env)
//
// Only keys that are missing are added; existing values are never changed. It prints key NAMES
// only, never values. Compose works without it (dev-only defaults); this is for anyone who wants
// secrets that are unique to their machine.
import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const GENERATED = {
  POSTGRES_PASSWORD: () => randomBytes(24).toString('base64url'),
  JWT_SECRET: () => randomBytes(48).toString('base64url'),
  SECRET_KEY_BASE: () => randomBytes(64).toString('hex'),
  // Realtime encrypts with AES-128: the key must be exactly 16 characters.
  REALTIME_DB_ENC_KEY: () => randomBytes(12).toString('base64url'),
  DASHBOARD_PASSWORD: () => randomBytes(18).toString('base64url'),
};

/**
 * @param {string} existing current contents of the .env file ('' if none)
 * @param {Record<string, () => string>} generators
 * @returns {{ text: string, added: string[] }}
 */
export function mergeEnv(existing, generators = GENERATED) {
  const present = new Set(
    existing
      .split('\n')
      .map((line) => /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/.exec(line)?.[1])
      .filter((key) => key !== undefined),
  );
  const lines = [];
  const added = [];
  for (const [key, make] of Object.entries(generators)) {
    if (!present.has(key)) {
      lines.push(`${key}=${make()}`);
      added.push(key);
    }
  }
  if (lines.length === 0) {
    return { text: existing, added };
  }
  const base = existing === '' || existing.endsWith('\n') ? existing : `${existing}\n`;
  const separator = base === '' ? '' : '\n';
  const header =
    '# Generated by scripts/gen-dev-env.mjs: random per-machine dev secrets. Never commit this file.\n';
  return { text: `${base}${separator}${header}${lines.join('\n')}\n`, added };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = process.argv[2] ?? '.env';
  const existing = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const { text, added } = mergeEnv(existing);
  if (added.length === 0) {
    console.log(`${file}: nothing to add, all keys already present`);
  } else {
    writeFileSync(file, text, { mode: 0o600 });
    chmodSync(file, 0o600);
    console.log(`${file}: added ${added.join(', ')}`);
    console.log(
      'If the stack was already started, run `make down` first (it removes the database volume):',
    );
    console.log('the database keeps the password it was first created with.');
  }
}
